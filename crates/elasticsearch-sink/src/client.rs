//! HTTP client implementation for Elasticsearch and `OpenSearch` clusters.

use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::Duration;

use bytes::Bytes;
use reqwest::header::{CONTENT_ENCODING, CONTENT_TYPE};
use serde::{Deserialize, Serialize};

use crate::config::{ElasticsearchAuthConfig, ElasticsearchSinkConfig};
use crate::error::ElasticsearchError;

/// Individual error details for a rejected bulk item action.
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
pub struct BulkItemError {
    /// Elasticsearch error type (e.g. `es_rejected_execution_exception`).
    #[serde(rename = "type", default)]
    pub error_type: String,
    /// Human-readable explanation of why the action was rejected.
    #[serde(default)]
    pub reason: String,
    /// Optional underlying cause details.
    #[serde(default)]
    pub caused_by: Option<serde_json::Value>,
}

/// Action item result details within a bulk response.
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
pub struct BulkItem {
    /// Target index or data stream backing index name.
    #[serde(rename = "_index", default)]
    pub index: Option<String>,
    /// Document identifier.
    #[serde(rename = "_id", default)]
    pub id: Option<String>,
    /// HTTP status code for this specific document operation.
    pub status: u16,
    /// Error details if the document operation failed.
    #[serde(default)]
    pub error: Option<BulkItemError>,
}

/// Action wrapper wrapping action-specific result object (`create`, `index`, `update`, `delete`).
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
pub struct BulkItemWrapper {
    /// Result for a create action.
    #[serde(default)]
    pub create: Option<BulkItem>,
    /// Result for an index action.
    #[serde(default)]
    pub index: Option<BulkItem>,
    /// Result for an update action.
    #[serde(default)]
    pub update: Option<BulkItem>,
    /// Result for a delete action.
    #[serde(default)]
    pub delete: Option<BulkItem>,
}

impl BulkItemWrapper {
    /// Returns a reference to the inner `BulkItem` regardless of action type.
    #[must_use]
    pub fn item(&self) -> Option<&BulkItem> {
        self.create
            .as_ref()
            .or(self.index.as_ref())
            .or(self.update.as_ref())
            .or(self.delete.as_ref())
    }

    /// Returns the HTTP status code of the inner action item, if present.
    #[must_use]
    pub fn status(&self) -> Option<u16> {
        self.item().map(|i| i.status)
    }

    /// Returns the error details of the inner action item, if present.
    #[must_use]
    pub fn error(&self) -> Option<&BulkItemError> {
        self.item().and_then(|i| i.error.as_ref())
    }

    /// Returns whether this item encountered a recoverable failure (HTTP 429 or 503).
    #[must_use]
    pub fn is_recoverable(&self) -> bool {
        self.status().is_some_and(|s| s == 429 || s == 503)
    }

    /// Returns whether this item encountered an unrecoverable failure (HTTP >= 400 except 429 and 503).
    #[must_use]
    pub fn is_unrecoverable(&self) -> bool {
        self.status()
            .is_some_and(|s| s >= 400 && s != 429 && s != 503)
    }
}

/// Top-level response structure returned by the Elasticsearch/`OpenSearch` Bulk API.
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
pub struct BulkResponse {
    /// Time in milliseconds spent by the cluster processing the bulk request.
    #[serde(default)]
    pub took: u64,
    /// Whether any document operations in the bulk request encountered an error.
    pub errors: bool,
    /// Array of action results for each document in the bulk request.
    #[serde(default)]
    pub items: Vec<BulkItemWrapper>,
}

impl BulkResponse {
    /// Returns the number of items that encountered a recoverable failure (HTTP 429 or 503).
    #[must_use]
    pub fn recoverable_count(&self) -> usize {
        self.items.iter().filter(|i| i.is_recoverable()).count()
    }

    /// Returns the number of items that encountered an unrecoverable failure (HTTP >= 400 except 429 and 503).
    #[must_use]
    pub fn unrecoverable_count(&self) -> usize {
        self.items.iter().filter(|i| i.is_unrecoverable()).count()
    }
}

/// Extracts line pairs (action line + document line) from an uncompressed NDJSON payload
/// for the specified item indices.
///
/// In NDJSON bulk format with autogenerated IDs, item index `i` maps to line `2*i` and line `2*i + 1`.
///
/// # Errors
///
/// Returns [`ElasticsearchError::Serialization`] if:
/// - The payload has an odd number of lines (incomplete action/document pair)
/// - Any requested item index is out of bounds
pub fn extract_sub_payload(
    payload: &[u8],
    item_indices: &[usize],
) -> Result<Bytes, ElasticsearchError> {
    if item_indices.is_empty() {
        return Ok(Bytes::new());
    }

    let mut line_ranges: Vec<(usize, usize)> = Vec::new();
    let mut line_start = 0;
    for (idx, &b) in payload.iter().enumerate() {
        if b == b'\n' {
            let line = &payload[line_start..=idx];
            if !line
                .iter()
                .all(|&c| c == b'\r' || c == b'\n' || c == b' ' || c == b'\t')
            {
                line_ranges.push((line_start, idx + 1));
            }
            line_start = idx + 1;
        }
    }
    if line_start < payload.len() {
        let line = &payload[line_start..];
        if !line
            .iter()
            .all(|&c| c == b'\r' || c == b'\n' || c == b' ' || c == b'\t')
        {
            line_ranges.push((line_start, payload.len()));
        }
    }

    if !line_ranges.len().is_multiple_of(2) {
        return Err(ElasticsearchError::Serialization(format!(
            "payload has an odd number of lines ({}), expected pairs of action and document lines",
            line_ranges.len()
        )));
    }

    let total_items = line_ranges.len() / 2;

    let mut total_bytes: usize = 0;
    for &idx in item_indices {
        if idx >= total_items {
            return Err(ElasticsearchError::Serialization(format!(
                "item index {idx} out of bounds for payload containing {total_items} items"
            )));
        }
        let action_start = line_ranges
            .get(2 * idx)
            .ok_or_else(|| {
                ElasticsearchError::Serialization(format!(
                    "missing action line range for item index {idx}"
                ))
            })?
            .0;
        let doc_end = line_ranges
            .get(2 * idx + 1)
            .ok_or_else(|| {
                ElasticsearchError::Serialization(format!(
                    "missing document line range for item index {idx}"
                ))
            })?
            .1;
        let item_len = doc_end.saturating_sub(action_start);
        total_bytes = total_bytes.saturating_add(item_len).saturating_add(1);
    }

    let mut buf = Vec::with_capacity(total_bytes);
    for &idx in item_indices {
        let action_start = line_ranges
            .get(2 * idx)
            .ok_or_else(|| {
                ElasticsearchError::Serialization(format!(
                    "missing action line range for item index {idx}"
                ))
            })?
            .0;
        let doc_end = line_ranges
            .get(2 * idx + 1)
            .ok_or_else(|| {
                ElasticsearchError::Serialization(format!(
                    "missing document line range for item index {idx}"
                ))
            })?
            .1;
        let slice = &payload[action_start..doc_end];
        buf.extend_from_slice(slice);
        if !slice.ends_with(b"\n") {
            buf.push(b'\n');
        }
    }

    Ok(Bytes::from(buf))
}

