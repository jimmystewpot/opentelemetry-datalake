/// High-performance HTTP client for Elasticsearch and `OpenSearch` clusters.
///
/// Manages connection pooling, client-side round-robin endpoint selection,
/// TLS configuration, authentication header injection, and retry loops.
#[derive(Debug, Clone)]
pub struct HttpClient {
    /// Underlying reqwest HTTP client with persistent connection pool.
    client: reqwest::Client,
    /// List of normalized cluster endpoint base URLs (without trailing slashes).
    endpoints: Vec<String>,
    /// Shared atomic counter for round-robin endpoint distribution.
    current_endpoint: Arc<AtomicUsize>,
    /// Configured authentication credentials.
    auth: ElasticsearchAuthConfig,
    /// Whether gzip compression is enabled for bulk request payloads.
    gzip_compression: bool,
    /// Maximum number of retry attempts for transient failures (429/503/network).
    max_retries: usize,
    /// Delay between retries in seconds.
    retry_interval_secs: u64,
}

impl HttpClient {
    /// Constructs a new `HttpClient` from the given sink configuration.
    ///
    /// Validates endpoint list, configures TLS root CA and verification options,
    /// sets connection and request timeouts, and initializes TCP keepalive.
    pub fn try_new(config: &ElasticsearchSinkConfig) -> Result<Self, ElasticsearchError> {
        if config.endpoints.is_empty() {
            return Err(ElasticsearchError::StartupValidation(
                "at least one endpoint must be configured".to_string(),
            ));
        }

        let endpoints: Vec<String> = config
            .endpoints
            .iter()
            .map(|ep| ep.trim().trim_end_matches('/').to_string())
            .collect();

        if endpoints.iter().any(String::is_empty) {
            return Err(ElasticsearchError::StartupValidation(
                "endpoint URL cannot be empty".to_string(),
            ));
        }

        let mut builder = reqwest::Client::builder()
            .connect_timeout(Duration::from_secs(config.connect_timeout_secs))
            .timeout(Duration::from_secs(config.request_timeout_secs))
            .tcp_keepalive(Duration::from_secs(60))
            .tcp_nodelay(true)
            .gzip(true);

        if config.tls.insecure_skip_verify {
            builder = builder.danger_accept_invalid_certs(true);
        }

        if let Some(ca_path) = &config.tls.ca_cert_path {
            let pem_bytes = std::fs::read(ca_path).map_err(|e| {
                ElasticsearchError::StartupValidation(format!(
                    "failed to read CA certificate from '{ca_path}': {e}"
                ))
            })?;
            let cert = reqwest::Certificate::from_pem(&pem_bytes)?;
            builder = builder.add_root_certificate(cert);
        }

        let client = builder.build()?;

        Ok(Self {
            client,
            endpoints,
            current_endpoint: Arc::new(AtomicUsize::new(0)),
            auth: config.auth.clone(),
            gzip_compression: config.gzip_compression,
            max_retries: config.max_retries,
            retry_interval_secs: config.retry_interval_secs,
        })
    }

    /// Returns the next cluster endpoint base URL in round-robin sequence.
    #[must_use]
    pub fn next_endpoint(&self) -> &str {
        let idx = self.current_endpoint.fetch_add(1, Ordering::Relaxed);
        &self.endpoints[idx % self.endpoints.len()]
    }

    /// Returns the slice of configured cluster endpoint base URLs.
    #[must_use]
    pub fn endpoints(&self) -> &[String] {
        &self.endpoints
    }

    /// Returns a reference to the active authentication configuration.
    #[must_use]
    pub fn auth(&self) -> &ElasticsearchAuthConfig {
        &self.auth
    }

    /// Returns whether gzip compression is enabled for bulk requests.
    #[must_use]
    pub const fn gzip_compression(&self) -> bool {
        self.gzip_compression
    }

    /// Injects authentication credentials into an outgoing HTTP request builder.
    pub fn apply_auth(&self, req: reqwest::RequestBuilder) -> reqwest::RequestBuilder {
        let default_url = self
            .endpoints
            .first()
            .map_or("http://localhost:9200", |s| s.as_str());
        self.apply_auth_request(req, "GET", default_url, &[])
    }

    /// Injects authentication credentials into an outgoing HTTP request builder with explicit
    /// HTTP method, target URL, and body content for signature calculation.
    #[cfg_attr(not(feature = "aws"), allow(unused_variables))]
    pub fn apply_auth_request(
        &self,
        req: reqwest::RequestBuilder,
        method: &str,
        url: &str,
        body: &[u8],
    ) -> reqwest::RequestBuilder {
        match &self.auth {
            ElasticsearchAuthConfig::None => req,
            ElasticsearchAuthConfig::Basic { username, password } => {
                req.basic_auth(username, password.as_deref())
            }
            ElasticsearchAuthConfig::ApiKey { api_key } => {
                req.header(reqwest::header::AUTHORIZATION, format!("ApiKey {api_key}"))
            }
            ElasticsearchAuthConfig::Bearer { token } => req.bearer_auth(token),
            #[cfg(feature = "aws")]
            ElasticsearchAuthConfig::AwsSigv4 { region, service } => {
                if let (Ok(key), Ok(secret)) = (
                    std::env::var("AWS_ACCESS_KEY_ID"),
                    std::env::var("AWS_SECRET_ACCESS_KEY"),
                ) {
                    let session_token = std::env::var("AWS_SESSION_TOKEN").ok();
                    self.apply_aws_sigv4(
                        req,
                        method,
                        url,
                        body,
                        region,
                        service,
                        &key,
                        &secret,
                        session_token.as_deref(),
                    )
                } else {
                    req
                }
            }
        }
    }

    /// Signs an outgoing request with AWS `SigV4` using explicit credentials and adds signature headers.
    #[cfg(feature = "aws")]
    #[allow(clippy::too_many_arguments)]
    pub fn apply_aws_sigv4(
        &self,
        mut req: reqwest::RequestBuilder,
        method: &str,
        url: &str,
        body: &[u8],
        region: &str,
        service: &str,
        access_key: &str,
        secret_key: &str,
        session_token: Option<&str>,
    ) -> reqwest::RequestBuilder {
        let creds = aws_credential_types::Credentials::new(
            access_key,
            secret_key,
            session_token.map(ToString::to_string),
            None,
            "elasticsearch-sink",
        );
        let identity = creds.into();
        let signing_settings = aws_sigv4::http_request::SigningSettings::default();
        let Ok(signing_params) = aws_sigv4::sign::v4::SigningParams::builder()
            .identity(&identity)
            .region(region)
            .name(service)
            .time(std::time::SystemTime::now())
            .settings(signing_settings)
            .build()
        else {
            return req;
        };

        let signing_params = signing_params.into();
        let signable_body = if body.is_empty() {
            aws_sigv4::http_request::SignableBody::Bytes(&[])
        } else {
            aws_sigv4::http_request::SignableBody::Bytes(body)
        };

        let Ok(signable_request) = aws_sigv4::http_request::SignableRequest::new(
            method,
            url,
            std::iter::empty(),
            signable_body,
        ) else {
            return req;
        };

        if let Ok(output) = aws_sigv4::http_request::sign(signable_request, &signing_params) {
            let (instructions, _sig) = output.into_parts();
            for (name, val) in instructions.headers() {
                req = req.header(name, val);
            }
        }
        req
    }

    /// Returns true if an HTTP status code indicates a transient error that should be retried.
    const fn is_transient_http_status(status: reqwest::StatusCode) -> bool {
        matches!(
            status,
            reqwest::StatusCode::TOO_MANY_REQUESTS
                | reqwest::StatusCode::SERVICE_UNAVAILABLE
                | reqwest::StatusCode::BAD_GATEWAY
                | reqwest::StatusCode::GATEWAY_TIMEOUT
        )
    }

    /// Merges items from a retry response into the aggregated `final_items` vector.
    fn merge_retry_items(
        final_items: &mut [BulkItemWrapper],
        active_indices: &[usize],
        retry_items: Vec<BulkItemWrapper>,
    ) {
        for (sub_idx, item_wrapper) in retry_items.into_iter().enumerate() {
            if let Some(&orig_idx) = active_indices
                .get(sub_idx)
                .filter(|&&idx| idx < final_items.len())
            {
                final_items[orig_idx] = item_wrapper;
            }
        }
    }

    /// Dispatches a single HTTP bulk request with round-robin endpoint selection, gzip compression, and authentication.
    async fn post_bulk_request(
        &self,
        data_stream: &str,
        payload: &Bytes,
    ) -> Result<reqwest::Response, ElasticsearchError> {
        let endpoint = self.next_endpoint();
        let url = format!("{endpoint}/{data_stream}/_bulk");

        let (body, is_gzipped) = if self.gzip_compression && !payload.is_empty() {
            let mut encoder =
                flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
            std::io::Write::write_all(&mut encoder, payload).map_err(|e| {
                ElasticsearchError::Serialization(format!("gzip compression failed: {e}"))
            })?;
            let compressed = encoder.finish().map_err(|e| {
                ElasticsearchError::Serialization(format!("gzip compression finalize failed: {e}"))
            })?;
            (Bytes::from(compressed), true)
        } else {
            (payload.clone(), false)
        };

        let mut req = self
            .client
            .post(&url)
            .header(CONTENT_TYPE, "application/x-ndjson")
            .body(body.clone());

        if is_gzipped {
            req = req.header(CONTENT_ENCODING, "gzip");
        }

        req = self.apply_auth_request(req, "POST", &url, &body);
        req.send().await.map_err(ElasticsearchError::Http)
    }

    /// Inspects items in the active sub-batch to identify recoverable failures and log unrecoverable failures.
    fn inspect_active_items(
        final_items: &[BulkItemWrapper],
        active_indices: &[usize],
    ) -> Vec<usize> {
        let mut recoverable_sub_indices = Vec::new();
        let mut unrecoverable_count: usize = 0;

        for (sub_idx, &orig_idx) in active_indices.iter().enumerate() {
            if let Some(item_wrapper) = final_items.get(orig_idx) {
                if item_wrapper.is_recoverable() {
                    recoverable_sub_indices.push(sub_idx);
                } else if item_wrapper.is_unrecoverable() {
                    unrecoverable_count = unrecoverable_count.saturating_add(1);
                    let err_type = item_wrapper
                        .error()
                        .map_or("unknown", |e| e.error_type.as_str());
                    let reason = item_wrapper.error().map_or("none", |e| e.reason.as_str());
                    let doc_id = item_wrapper
                        .item()
                        .and_then(|i| i.id.as_deref())
                        .unwrap_or("none");
                    let index_name = item_wrapper
                        .item()
                        .and_then(|i| i.index.as_deref())
                        .unwrap_or("none");
                    tracing::warn!(
                        orig_index = orig_idx,
                        status = item_wrapper.status().unwrap_or(0),
                        index = %index_name,
                        doc_id = %doc_id,
                        error_type = %err_type,
                        reason = %reason,
                        "Elasticsearch bulk item rejected with unrecoverable error"
                    );
                }
            }
        }

        if unrecoverable_count > 0 {
            tracing::warn!(
                unrecoverable_count = unrecoverable_count,
                "Bulk request contained unrecoverable item errors; dropped non-retryable documents"
            );
        }

        recoverable_sub_indices
    }

    /// Sends a serialized NDJSON bulk payload targeting `POST /<data_stream>/_bulk`.
    ///
    /// Applies round-robin node selection, gzip compression (if enabled), authentication,
    /// and a jittered exponential backoff retry loop on transient failures (429/503/network).
    ///
    /// When the bulk response indicates errors (`errors: true`):
    /// - Unrecoverable item failures (HTTP 400, etc.) are logged at WARN level and dropped.
    /// - Recoverable item failures (HTTP 429, 503) are extracted by index and re-submitted
    ///   as a retry sub-payload with jittered exponential backoff and node failover.
    /// - Retries continue up to `max_retries`. If retries are exhausted and recoverable
    ///   failures remain, returns [`ElasticsearchError::BulkFailed`].
    pub async fn send_bulk(
        &self,
        data_stream: &str,
        payload: Bytes,
    ) -> Result<BulkResponse, ElasticsearchError> {
        let data_stream = data_stream.trim_matches('/');
        let max_attempts = self.max_retries.saturating_add(1);
        let mut attempt: usize = 0;

        let mut current_payload = payload;
        let mut active_indices: Vec<usize> = Vec::new();
        let mut final_items: Vec<BulkItemWrapper> = Vec::new();
        let mut total_took: u64 = 0;

        loop {
            match self.post_bulk_request(data_stream, &current_payload).await {
                Ok(response) => {
                    let status = response.status();

                    if Self::is_transient_http_status(status) {
                        attempt = attempt.saturating_add(1);
                        if attempt >= max_attempts {
                            return Err(ElasticsearchError::BulkFailed {
                                retries: self.max_retries,
                                message: format!("HTTP {status} after {attempt} attempts"),
                            });
                        }
                        self.sleep_backoff(attempt).await;
                        continue;
                    }

                    if status == reqwest::StatusCode::UNAUTHORIZED
                        || status == reqwest::StatusCode::FORBIDDEN
                    {
                        let err_text = response.text().await.unwrap_or_default();
                        return Err(ElasticsearchError::AuthenticationFailed(format!(
                            "HTTP {status}: {err_text}"
                        )));
                    }

                    if !status.is_success() {
                        let err_text = response.text().await.unwrap_or_default();
                        return Err(ElasticsearchError::BulkFailed {
                            retries: attempt,
                            message: format!("HTTP {status}: {err_text}"),
                        });
                    }

                    let bulk_resp: BulkResponse =
                        response.json().await.map_err(ElasticsearchError::Http)?;

                    total_took = total_took.saturating_add(bulk_resp.took);

                    if final_items.is_empty() {
                        if !bulk_resp.errors {
                            return Ok(bulk_resp);
                        }
                        final_items = bulk_resp.items;
                        active_indices = (0..final_items.len()).collect();
                    } else {
                        Self::merge_retry_items(&mut final_items, &active_indices, bulk_resp.items);
                    }

                    let recoverable_sub_indices =
                        Self::inspect_active_items(&final_items, &active_indices);

                    if recoverable_sub_indices.is_empty() {
                        let has_errors = final_items.iter().any(BulkItemWrapper::is_unrecoverable);
                        return Ok(BulkResponse {
                            took: total_took,
                            errors: has_errors,
                            items: final_items,
                        });
                    }

                    attempt = attempt.saturating_add(1);
                    if attempt >= max_attempts {
                        return Err(ElasticsearchError::BulkFailed {
                            retries: self.max_retries,
                            message: format!(
                                "{} items failed with recoverable status (429/503) after {} retries",
                                recoverable_sub_indices.len(),
                                self.max_retries
                            ),
                        });
                    }

                    current_payload =
                        extract_sub_payload(&current_payload, &recoverable_sub_indices)?;
                    active_indices = recoverable_sub_indices
                        .into_iter()
                        .filter_map(|sub_idx| active_indices.get(sub_idx).copied())
                        .collect();

                    self.sleep_backoff(attempt).await;
                }
                Err(err) => {
                    attempt = attempt.saturating_add(1);
                    if attempt >= max_attempts {
                        return Err(ElasticsearchError::BulkFailed {
                            retries: self.max_retries,
                            message: format!("network error after {attempt} attempts: {err}"),
                        });
                    }
                    self.sleep_backoff(attempt).await;
                }
            }
        }
    }

    /// Performs a startup cluster health check by sending `GET /`.
    ///
    /// Validates that the cluster is reachable, authenticated, and returns a valid version number.
    pub async fn health_check(&self) -> Result<(), ElasticsearchError> {
        let endpoint = self.next_endpoint();
        let url = format!("{endpoint}/");

        let req = self.client.get(&url);
        let req = self.apply_auth_request(req, "GET", &url, &[]);

        let response = req.send().await.map_err(|e| {
            ElasticsearchError::StartupValidation(format!(
                "failed to connect to cluster endpoint '{endpoint}': {e}"
            ))
        })?;

        let status = response.status();
        if status == reqwest::StatusCode::UNAUTHORIZED || status == reqwest::StatusCode::FORBIDDEN {
            return Err(ElasticsearchError::AuthenticationFailed(format!(
                "health check authentication failed with HTTP {status}"
            )));
        }

        if !status.is_success() {
            return Err(ElasticsearchError::StartupValidation(format!(
                "health check against '{endpoint}' returned HTTP {status}"
            )));
        }

        let info: ClusterInfo = response.json().await.map_err(|e| {
            ElasticsearchError::StartupValidation(format!(
                "failed to parse cluster info JSON from '{endpoint}': {e}"
            ))
        })?;

        let version_number = info
            .version
            .map(|v| v.number)
            .filter(|n| !n.trim().is_empty())
            .ok_or_else(|| {
                ElasticsearchError::StartupValidation(format!(
                    "cluster info from '{endpoint}' did not contain a valid version number"
                ))
            })?;

        tracing::info!(
            endpoint = %endpoint,
            version = %version_number,
            "Elasticsearch/OpenSearch cluster health check succeeded"
        );

        Ok(())
    }

    /// Validates that a composable index template exists for the given data stream.
    ///
    /// Queries `GET /_index_template/<data_stream>` and returns an error if not found.
    pub async fn validate_index_template(
        &self,
        data_stream: &str,
    ) -> Result<(), ElasticsearchError> {
        let data_stream = data_stream.trim_matches('/');
        let endpoint = self.next_endpoint();
        let url = format!("{endpoint}/_index_template/{data_stream}");

        let req = self.client.get(&url);
        let req = self.apply_auth_request(req, "GET", &url, &[]);

        let response = req.send().await.map_err(|e| {
            ElasticsearchError::StartupValidation(format!(
                "failed to query index template for '{data_stream}' on '{endpoint}': {e}"
            ))
        })?;

        let status = response.status();
        if status == reqwest::StatusCode::NOT_FOUND {
            return Err(ElasticsearchError::StartupValidation(format!(
                "index template for data stream '{data_stream}' not found (HTTP 404)"
            )));
        }

        if status == reqwest::StatusCode::UNAUTHORIZED || status == reqwest::StatusCode::FORBIDDEN {
            return Err(ElasticsearchError::AuthenticationFailed(format!(
                "unauthorized to validate index template for '{data_stream}': HTTP {status}"
            )));
        }

        if !status.is_success() {
            let body = response.text().await.unwrap_or_default();
            return Err(ElasticsearchError::StartupValidation(format!(
                "index template check for '{data_stream}' returned HTTP {status}: {body}"
            )));
        }

        let parsed: IndexTemplatesResponse = response.json().await.map_err(|e| {
            ElasticsearchError::StartupValidation(format!(
                "failed to parse index templates response for '{data_stream}': {e}"
            ))
        })?;

        if parsed.index_templates.is_empty() {
            return Err(ElasticsearchError::StartupValidation(format!(
                "index template for data stream '{data_stream}' returned empty template list"
            )));
        }

        tracing::info!(
            endpoint = %endpoint,
            data_stream = %data_stream,
            "Index template validation succeeded"
        );

        Ok(())
    }

    /// Executes a jittered exponential backoff sleep.
    async fn sleep_backoff(&self, attempt: usize) {
        if self.retry_interval_secs == 0 {
            tokio::task::yield_now().await;
            return;
        }

        let base_ms = self.retry_interval_secs.saturating_mul(1000).max(100);
        let shift = attempt.saturating_sub(1).min(6);
        let multiplier = 1u64 << shift;
        let base_backoff = base_ms.saturating_mul(multiplier);

        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.subsec_nanos());
        let jitter_ms = u64::from(nanos % 500);

        let total_backoff_ms = base_backoff.saturating_add(jitter_ms);
        tokio::time::sleep(Duration::from_millis(total_backoff_ms)).await;
    }
}

